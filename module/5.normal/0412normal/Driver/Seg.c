#include <Seg.h>

unsigned char Seg_dula[] = {0xc0,0xf9,0xa4,0xb0,0x99,0x92,0x82,0xf8,0x80,0x90,0xff,0x88};
unsigned char Seg_wela[] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80};

void Seg_Disp(unsigned char wela,dula,point)
{
	unsigned char temp;
	
	P0 = 0xff;
	temp = P2 & 0x1f;
	temp = temp | 0xe0;
	P2 = temp;
	temp = P2 & 0x1f;
	P2 = temp;
	
	P0 = Seg_wela[wela];
	temp = P2 & 0x1f;
	temp = temp | 0xc0;
	P2 = temp;
	temp = P2 & 0x1f;
	P2 = temp;
	
	P0 = Seg_dula[dula];
	if(point) P0 &= 0x7f;
	temp = P2 & 0x1f;
	temp = temp | 0xe0;
	P2 = temp;
	temp = P2 & 0x1f;
	P2 = temp;	

}