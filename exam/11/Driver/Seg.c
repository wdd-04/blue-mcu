#include <Seg.h>
//共阳极数码管，0点亮
unsigned char seg_dula[] = {0xc0,0xf9,0xa4,0xb0,0x99,0x92,0x82,0xf8,0x80,0x90,0xff,0xc6,0x8c};
unsigned char seg_wela[] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80};

void Seg_Disp(unsigned char wela,dula,point)
{
	P0 = 0xff;//消影
	P2 = P2 & 0x1f | 0xe0;//选中Y7C锁存器
	P2 &= 0x1f;//关闭Y7c锁存器
	
	P0 = seg_wela[wela];//位选
	P2 = P2 & 0x1f | 0xc0;//选中Y6C锁存器
	P2 &= 0x1f;//关闭Y6c锁存器
	
	if(point)//段选
		P0 = seg_dula[dula] & 0x7f;	
	else
		P0 = seg_dula[dula];
	P2 = P2 & 0x1f | 0xe0;//选中Y7C锁存器
	P2 &= 0x1f;//关闭Y7c锁存器
}