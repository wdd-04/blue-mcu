#include <Seg.h>

unsigned char Seg_dula[] = {
0xc0, //0
0xf9, //1
0xa4, //2
0xb0, //3
0x99, //4
0x92, //5
0x82, //6
0xf8, //7
0x80, //8
0x90, //9
0xff //无	
};
unsigned char Seg_wela[] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80};

void Seg_Disp(unsigned char wela,dula,point)
{
	P0 = 0xff;
	P2 = P2 & 0x1f | 0xe0;
	P2 &= 0x1f;

	P0 = Seg_wela[wela];
	P2 = P2 & 0x1f | 0xc0;
	P2 &= 0x1f;
	
	if(point)
		P0 = Seg_dula[dula] & 0x7f;
	else
		P0 = Seg_dula[dula];
	P2 = P2 & 0x1f | 0xe0;
	P2 &= 0x1f;
}